/**
 * Пресет стилистики — это описание регистра, а не шаблон текста.
 *
 * Живёт в репозитории, а не в базе: его правят с ревью, потому что ошибка
 * в регистре портит все материалы, сгенерированные потом. И собирается он
 * генератором промта единообразно — добавление пресета не требует правок
 * в коде генерации.
 */

/** Насколько проработан пресет для конкретного языка. */
export type PresetQuality = "full" | "draft";

export interface SpeakerRole {
  /** Как роль называется в скрипте: «Moderator», «Researcher» */
  role: string;
  /** На чём этот спикер сосредоточен — задаёт спор между репликами */
  focus: string;
}

export interface StylePreset {
  id: string;
  label: string;

  /**
   * Качество по языкам. Отсутствие языка означает, что пресет для него
   * не готов вовсе и выбрать его будет нельзя.
   */
  languages: Partial<Record<string, PresetQuality>>;

  /** Где это звучит — одна фраза для интерфейса */
  setting: string;

  /** Регистр и синтаксис. Уходит в промт почти дословно. */
  register: string;

  /** Типовые роли. Модель берёт столько, сколько просит параметр проекта. */
  speakerRoles: SpeakerRole[];

  /** Процедурная лексика: уместная и недопустимая в этом формате */
  vocabulary: {
    encouraged: string[];
    forbidden: string[];
  };

  /** Откуда брать эквиваленты для глоссария */
  terminologySources: string[];

  /** Характер статистики: какие цифры уместны и как они подаются */
  statistics: string;

  /** Чего избегать сверх общих правил */
  avoid: string[];
}
