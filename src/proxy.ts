import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";
import { SESSION_COOKIE, readToken } from "@/lib/session";

/**
 * Защита админки Payload.
 *
 * Паролей нет, и собственная форма входа Payload здесь бесполезна — вводить
 * в неё нечего. Неавторизованного отправляем на наш вход по коду; сессионная
 * кука после него откроет и админку, стратегия одна на оба.
 *
 * Почему здесь, а не в самой странице. Пробовал `redirect()` в компоненте —
 * не работает: разметку админки Payload успевает отдать раньше, чем
 * досчитывается асинхронный компонент, заголовки уже ушли с кодом 200,
 * и редирект вырождается в клиентский. Браузер по нему уйдёт, но оболочку
 * админки посторонний всё же получит, а `curl` останется на 200.
 * Проверка до отрисовки такого не допускает — отсюда настоящий 307.
 *
 * Подпись проверяется здесь же — это чистая криптография, без обращения
 * к базе. Проверять одно лишь наличие куки было бы недостаточно: любое
 * значение открывало бы оболочку админки. Данных Payload такому не отдаст,
 * но и разметку показывать постороннему незачем.
 */
export function proxy(request: NextRequest) {
  const userId = readToken(request.cookies.get(SESSION_COOKIE)?.value);
  if (userId) return NextResponse.next();

  const target = new URL("/", request.url);
  return NextResponse.redirect(target, 307);
}

export const config = {
  // Только админка. Приложение свои маршруты закрывает само, а лишняя
  // проверка на каждом запросе — лишняя задержка.
  matcher: ["/admin/:path*", "/admin"],
};
