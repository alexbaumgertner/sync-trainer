/**
 * Допуск к кроновым маршрутам.
 *
 * Раньше в каждом маршруте стояло `!secret || заголовок совпал`, то есть
 * **отсутствие секрета открывало маршрут**. На боевом секрет задан, и это
 * никогда не стреляло, — но превью-развёртывания его не получают (переменная
 * выдана только продакшену), а база у превью заведена веткой от боевой, то
 * есть с настоящими данными людей. Маршрут копии на стенде отдавал бы дамп
 * этой базы любому, кто до него дотянется.
 *
 * Сейчас стенд закрыт входом Vercel, и дотянуться нельзя. Но это защита
 * снаружи, которую выключают одной галочкой в панели, — а маршрут обязан
 * защищаться сам.
 *
 * Без секрета открыто только вне облака: локально задавать его незачем,
 * а в любом развёртывании его отсутствие — это ошибка настройки, и вести
 * себя она должна как запрет, а не как разрешение.
 */
export function cronAuthorized(request: Request): boolean {
  const secret = process.env.CRON_SECRET?.trim();
  if (secret) return request.headers.get("authorization") === `Bearer ${secret}`;
  return !process.env.VERCEL_ENV;
}

export const CRON_FORBIDDEN = "Нужен CRON_SECRET.";
