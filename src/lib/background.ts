import { after } from "next/server";

/**
 * Запускает работу после ответа.
 *
 * Основной путь — `after` из Next: он держит инстанс живым до конца работы
 * в пределах `maxDuration` маршрута. Но он требует контекста запроса и вне
 * его выбрасывает — так бывает в тестах, в скриптах и в любом окружении,
 * которое однажды перестанет быть Vercel.
 *
 * Молча потерять работу в этом случае нельзя: запись о генерации уже создана,
 * ответ уже ушёл, и человек будет ждать файла, которого никто не делает.
 * Поэтому запасной путь — запустить без ожидания. Если окружение не даст ей
 * дожить до конца, работа будет опознана как оборванная по времени
 * (`lib/generations.ts`), и человек увидит «прервано», а не вечное «идёт».
 */
export function runAfterResponse(work: () => Promise<void>): void {
  try {
    after(work);
  } catch (error) {
    console.warn("[background] after недоступен, работа пойдёт без него", error);
    void work().catch((nested: unknown) => {
      console.error("[background] работа упала", nested);
    });
  }
}
