/**
 * Путь артефакта в хранилище. Вынесено в отдельный модуль без зависимостей
 * намеренно: форму пути должны знать и `src/lib/artifacts.ts` (он пишет),
 * и слой доступа (он проверяет). Продублируй строку в двух местах — и они
 * разойдутся ровно тогда, когда проверка перестанет ловить подмену.
 */

/**
 * Приставка окружения. Хранилище Blob у превью и боевого — ОДНО (токен выдан
 * обоим окружениям), а базы разные: превью-развёртыванию Neon подставляет
 * ветку. Значит счётчики идентификаторов у них разошлись, и однажды проект 4
 * на стенде и проект 4 на боевом — разные проекты с одним путём файла.
 * Стенд молча переписал бы человеку скрипт, по которому тот готовится.
 *
 * У боевого приставки нет: пути уже записаны в базе, и менять их задним
 * числом значит потерять доступ к существующим файлам. Вне Vercel приставки
 * тоже нет — локально файлы лежат на диске, не в Blob.
 */
const envPrefix = (): string => {
  const env = process.env.VERCEL_ENV;
  return !env || env === "production" ? "" : `${env}/`;
};

export const artifactPrefix = (projectId: number | string): string =>
  `${envPrefix()}projects/${projectId}/`;

export const artifactPath = (projectId: number, name: string): string =>
  `${artifactPrefix(projectId)}${name}`;

/**
 * Лежит ли путь внутри каталога проекта в ТЕКУЩЕМ окружении.
 *
 * Имя проверяется целиком: `..` в пути и вложенные каталоги отвергаются.
 * Одного `startsWith` мало — `projects/7/../8/script.md` начинается правильно,
 * а указывает в чужой проект.
 *
 * Следствие приставки: на превью-стенде файлы, записанные боевым, считаются
 * посторонними и не отдаются. Так и задумано — стенд копия базы, а не
 * зеркало хранилища, и читать боевые файлы ему незачем.
 */
export function insideProject(blobPath: string, projectId: number | string): boolean {
  const prefix = artifactPrefix(projectId);
  if (!blobPath.startsWith(prefix)) return false;

  const name = blobPath.slice(prefix.length);
  return name.length > 0 && !name.includes("/");
}
