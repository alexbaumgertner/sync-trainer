import type { ErrorEvent } from "@sentry/nextjs";

/**
 * Общие настройки сбора ошибок — одни на сервер и на браузер.
 *
 * Зачем он вообще. Все поломки этого релиза нашёл человек, глядевший
 * в экран в момент сбоя. С посторонними людьми смотреть будет некому,
 * а логи на Hobby короткие: ошибка, случившаяся ночью, к утру недоступна.
 *
 * Главное решение здесь — не «включить», а «что не отправлять». Наши
 * пользователи работают с материалами заказчиков под NDA, и трассировка
 * ошибки — самое естественное место, куда эти материалы утекут: в теле
 * запроса лежит текст документа, в переменных — термины глоссария.
 * Поэтому отправляется только то, что нужно для починки: где упало и с
 * какой ошибкой. Содержимое запросов вырезается целиком.
 */

export const SENTRY_DSN = process.env.NEXT_PUBLIC_SENTRY_DSN?.trim() || undefined;

/**
 * Что вырезаем из события перед отправкой.
 *
 * Список разрешённого, а не запрещённого, был бы надёжнее, но Sentry
 * такого не даёт. Поэтому вырезаем по месту и держим список коротким:
 * всё, что может содержать пользовательский текст.
 */
export function scrub(event: ErrorEvent): ErrorEvent | null {
  if (event.request) {
    // Тело запроса — это текст документа на загрузке и SSML на синтезе.
    delete event.request.data;
    delete event.request.cookies;
    delete event.request.headers;
    // Адрес оставляем, но без строки запроса: в ней бывают адреса почты.
    if (event.request.url) event.request.url = event.request.url.split("?")[0];
  }

  // Локальные переменные в трассировке — второй путь для того же текста.
  for (const value of event.exception?.values ?? []) {
    for (const frame of value.stacktrace?.frames ?? []) delete frame.vars;
  }

  // Хлебные крошки браузера хранят значения полей формы.
  delete event.breadcrumbs;

  return event;
}

export const commonOptions = {
  dsn: SENTRY_DSN,
  // Ключа нет — SDK молчит. Так и должно быть локально и в тестах.
  enabled: Boolean(SENTRY_DSN),
  environment: process.env.VERCEL_ENV ?? "development",
  // Имя и адрес пользователя не собираем: для починки они не нужны,
  // а бесплатный тариф не повод хранить чужие данные у третьей стороны.
  sendDefaultPii: false,
  // Замеры скорости выключены намеренно: они съедают бесплатный лимит,
  // а быстродействие мы уже меряем трассировкой и Lighthouse.
  tracesSampleRate: 0,
  beforeSend: scrub,
};
