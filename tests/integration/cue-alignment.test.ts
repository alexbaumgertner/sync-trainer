import { describe, expect, it } from "vitest";
import { alignToPauses, buildCues, realignVtt, type Pause } from "@/lib/cues";

/**
 * Границы фраз, притянутые к паузам в звуке.
 *
 * Найдено живым использованием: к середине озвучки подсветка убегала
 * вперёд на две фразы. Причина не в длительностях — они точны по кадрам
 * MP3, — а в том, что ВНУТРИ реплики фразы раскладывались пропорционально
 * длине текста. Допущение «речь идёт с постоянным числом символов
 * в секунду» на настоящей озвучке не держится: между голосами разброс
 * оказался от 14,5 до 25,1 символа в секунду.
 *
 * Здесь проверяется не «стало лучше» — это словами не измеришь, — а
 * четыре свойства, без которых привязка опаснее её отсутствия: границы
 * не переставляются, фраза не схлопывается, далёкая пауза не притягивает,
 * и при отсутствии пауз всё остаётся как было.
 */

const pause = (time: number, length = 0.3): Pause => ({ time, length });

describe("привязка к паузам", () => {
  it("границу двигает к близкой паузе", () => {
    // Предсказание промахнулось на полсекунды — пауза стоит рядом
    const result = alignToPauses([10], [pause(10.5)], 0, 20);
    expect(result).toEqual([10.5]);
  });

  it("из двух пауз выбирает более длинную — конец предложения, не запятую", () => {
    const result = alignToPauses([10], [pause(9.6, 0.2), pause(10.4, 0.5)], 0, 20);
    expect(result).toEqual([10.4]);
  });

  it("далёкую паузу не трогает: это уже другая фраза", () => {
    const result = alignToPauses([10], [pause(16)], 0, 20);
    expect(result).toEqual([10]);
  });

  it("без пауз возвращает предсказание нетронутым", () => {
    expect(alignToPauses([5, 10, 15], [], 0, 20)).toEqual([5, 10, 15]);
  });
});

describe("привязка не ломает раскладку", () => {
  it("границы остаются по возрастанию", () => {
    // Жадный выбор «ближайшая длинная пауза» однажды переставил границы
    // местами и дал фразу отрицательной длины. Здесь паузы расставлены
    // так, чтобы соблазнить именно на это.
    const pauses = [pause(4, 0.6), pause(5, 0.2), pause(4.2, 0.55), pause(12, 0.6)];
    const result = alignToPauses([5, 10, 15], pauses, 0, 20);

    for (let i = 1; i < result.length; i++) {
      expect(result[i]).toBeGreaterThan(result[i - 1]);
    }
  });

  it("фраза не схлопывается в точку", () => {
    /**
     * Две длинные паузы стоят рядом, и обе близко к своим предсказаниям:
     * по расстоянию выгодно занять обе — но тогда между ними останется
     * двести миллисекунд, а там целое предложение.
     *
     * Первая версия этого теста ничего не проверяла: границы там отсекало
     * ограничение на дальность, и снятие проверки длины оставляло его
     * зелёным. Числа подобраны так, чтобы держала именно длина.
     */
    const result = alignToPauses([5, 8], [pause(7.9, 0.6), pause(8.1, 0.6)], 0, 20);

    expect(result[1] - result[0]).toBeGreaterThan(1.6);
  });

  it("все границы остаются внутри реплики", () => {
    const result = alignToPauses([5, 10], [pause(0.2), pause(19.9)], 0, 20);

    for (const time of result) {
      expect(time).toBeGreaterThan(0);
      expect(time).toBeLessThan(20);
    }
  });
});

describe("карта времени целиком", () => {
  const item = {
    kind: "speech" as const,
    speaker: "Модератор",
    text: "Первое предложение. Второе предложение длиннее первого. Третье.",
    seconds: 30,
  };

  it("без пауз раскладка прежняя, пропорциональная", () => {
    const cues = buildCues([item]);

    expect(cues).toHaveLength(3);
    expect(cues[0].start).toBe(0);
    expect(cues[2].end).toBe(30);
  });

  it("с паузами границы встают на них", () => {
    const cues = buildCues([item], [pause(12, 0.5), pause(24, 0.5)]);

    expect(cues[0].end).toBe(12);
    expect(cues[1].start).toBe(12);
    expect(cues[1].end).toBe(24);
    // Фразы идут встык: разрыв означал бы мгновение без подсветки
    expect(cues[2].start).toBe(24);
    expect(cues[2].end).toBe(30);
  });
});

describe("пересчёт готовой карты", () => {
  const vtt = [
    "WEBVTT",
    "",
    "1",
    "00:00:00.000 --> 00:00:10.000",
    "<v Модератор>Первое предложение.</v>",
    "",
    "2",
    "00:00:10.000 --> 00:00:30.000",
    "<v Модератор>Второе предложение.</v>",
    "",
  ].join("\n");

  it("двигает границу к паузе, не трогая начало и конец реплики", () => {
    const next = realignVtt(vtt, [pause(11.5, 0.5)]);

    expect(next).toContain("00:00:11.500");
    expect(next).toContain("00:00:00.000");
    expect(next).toContain("00:00:30.000");
    // Текст и говорящий переживают пересчёт
    expect(next).toContain("<v Модератор>Второе предложение.</v>");
  });

  it("без пауз оставляет карту как есть", () => {
    const next = realignVtt(vtt, []);

    expect(next).toContain("00:00:10.000");
  });

  it("на пустой карте отвечает отказом, а не пустой строкой", () => {
    expect(realignVtt("WEBVTT\n\n", [pause(5)])).toBeNull();
  });
});
